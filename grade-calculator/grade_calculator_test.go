	gradeCalculator := NewGradeCalculator()

	// assignments avg 85, exams avg 75, essays avg 90 -> 42.5 + 26.25 + 13.5 = 82.25
	gradeCalculator.AddGrade("assignment 1", 80, Assignment)
	gradeCalculator.AddGrade("assignment 2", 90, Assignment)
